
"""Tests for safe AI usage record cleanup."""

from datetime import datetime, timedelta, timezone

import pytest
from sqlalchemy import create_engine, func, select
from sqlalchemy.orm import sessionmaker

from backend.ai import cleanup_usage
from backend.ai.cleanup_usage import (
    AIUsageCleanupUnavailable,
    cleanup_ai_usage,
)
from backend.database.connection import engine
from backend.database.models import AIExtractionAttempt


@pytest.fixture
def usage_sessions():
    """Use an isolated PostgreSQL temporary table."""

    with engine.connect() as connection:
        outer_transaction = connection.begin()

        connection.exec_driver_sql(
            """
            CREATE TEMP TABLE ai_extraction_attempts (
                id INTEGER GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                visitor_hash VARCHAR(64) NOT NULL,
                created_at TIMESTAMPTZ NOT NULL
                    DEFAULT CURRENT_TIMESTAMP,
                lease_expires_at TIMESTAMPTZ NOT NULL,
                status VARCHAR(20) NOT NULL
                    DEFAULT 'reserved'
            ) ON COMMIT DROP
            """
        )

        try:
            yield sessionmaker(
                bind=connection,
                expire_on_commit=False,
                join_transaction_mode="create_savepoint",
            )

        finally:
            outer_transaction.rollback()


def make_attempt(
    visitor,
    *,
    days_ago,
    lease_seconds_from_now,
    status,
):
    now = datetime.now(timezone.utc)

    return AIExtractionAttempt(
        visitor_hash=visitor * 64,
        created_at=(
            now - timedelta(days=days_ago)
        ),
        lease_expires_at=(
            now
            + timedelta(
                seconds=lease_seconds_from_now
            )
        ),
        status=status,
    )


def record_count(factory):
    with factory() as session:
        return session.scalar(
            select(
                func.count(AIExtractionAttempt.id)
            )
        )


def test_dry_run_does_not_delete(usage_sessions):
    with usage_sessions.begin() as session:
        session.add_all([
            make_attempt(
                "a",
                days_ago=60,
                lease_seconds_from_now=-3600,
                status="completed",
            ),
            make_attempt(
                "b",
                days_ago=10,
                lease_seconds_from_now=-3600,
                status="failed",
            ),
        ])

    result = cleanup_ai_usage(
        usage_sessions
    )

    assert result.applied is False
    assert result.candidates == 1
    assert result.deleted == 0
    assert record_count(usage_sessions) == 2


def test_apply_deletes_only_expired_history(
    usage_sessions,
):
    with usage_sessions.begin() as session:
        session.add_all([
            make_attempt(
                "a",
                days_ago=60,
                lease_seconds_from_now=-3600,
                status="completed",
            ),
            make_attempt(
                "b",
                days_ago=50,
                lease_seconds_from_now=-3600,
                status="failed",
            ),
            make_attempt(
                "c",
                days_ago=70,
                lease_seconds_from_now=-3600,
                status="reserved",
            ),
            make_attempt(
                "d",
                days_ago=10,
                lease_seconds_from_now=-3600,
                status="completed",
            ),
        ])

    result = cleanup_ai_usage(
        usage_sessions,
        apply=True,
    )

    assert result.applied is True
    assert result.candidates == 3
    assert result.deleted == 3
    assert record_count(usage_sessions) == 1

    # Running cleanup again must be safe.
    second_result = cleanup_ai_usage(
        usage_sessions,
        apply=True,
    )

    assert second_result.deleted == 0
    assert record_count(usage_sessions) == 1


def test_active_lease_is_never_deleted(
    usage_sessions,
):
    with usage_sessions.begin() as session:
        session.add_all([
            make_attempt(
                "a",
                days_ago=70,
                lease_seconds_from_now=3600,
                status="reserved",
            ),
            make_attempt(
                "b",
                days_ago=70,
                lease_seconds_from_now=-3600,
                status="failed",
            ),
        ])

    result = cleanup_ai_usage(
        usage_sessions,
        apply=True,
    )

    assert result.deleted == 1

    with usage_sessions() as session:
        remaining = session.scalars(
            select(AIExtractionAttempt)
        ).all()

    assert len(remaining) == 1
    assert remaining[0].visitor_hash == "a" * 64
    assert remaining[0].status == "reserved"


