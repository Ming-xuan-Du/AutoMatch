def test_non_postgres_cleanup_is_rejected():
    sqlite_engine = create_engine(
        "sqlite+pysqlite:///:memory:"
    )

    factory = sessionmaker(
        bind=sqlite_engine
    )

    with pytest.raises(
        AIUsageCleanupUnavailable
    ):
        cleanup_ai_usage(
            factory,
            apply=True,
        )

    sqlite_engine.dispose()


def test_cli_requires_explicit_apply(
    usage_sessions,
    monkeypatch,
    capsys,
):
    monkeypatch.setattr(
        cleanup_usage,
        "SessionLocal",
        usage_sessions,
    )

    with usage_sessions.begin() as session:
        session.add(
            make_attempt(
                "a",
                days_ago=60,
                lease_seconds_from_now=-3600,
                status="completed",
            )
        )

    assert cleanup_usage.main([]) == 0

    output = capsys.readouterr().out

    assert "DRY RUN" in output
    assert "Deleted records: 0" in output
    assert record_count(usage_sessions) == 1

    assert cleanup_usage.main(["--apply"]) == 0

    output = capsys.readouterr().out

    assert "Mode: APPLY" in output
    assert "Deleted records: 1" in output
    assert record_count(usage_sessions) == 0
