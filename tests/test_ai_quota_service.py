def test_expired_lease_does_not_block_forever(
    quota_sessions,
):
    first_id = reserve_ai_extraction(
        quota_sessions,
        "a" * 64,
    )

    with quota_sessions.begin() as session:
        session.execute(
            update(AIExtractionAttempt)
            .where(AIExtractionAttempt.id == first_id)
            .values(
                lease_expires_at=(
                    "2000-01-01T00:00:00+00:00"
                )
            )
        )

    second_id = reserve_ai_extraction(
        quota_sessions,
        "b" * 64,
    )

    assert second_id != first_id


def test_non_postgres_storage_is_rejected():
    sqlite_engine = create_engine(
        "sqlite+pysqlite:///:memory:"
    )

    factory = sessionmaker(bind=sqlite_engine)

    with pytest.raises(AIQuotaUnavailable):
        reserve_ai_extraction(
            factory,
            "a" * 64,
        )

    sqlite_engine.dispose()


def test_postgres_quota_lock_is_exclusive():
    """Two DB connections cannot hold the same quota lock."""

    with engine.connect() as first:
        with engine.connect() as second:
            with first.begin():
                first.execute(
                    text(
                        "SELECT pg_advisory_xact_lock(:key)"
                    ),
                    {"key": QUOTA_LOCK_KEY},
                )

                with second.begin():
                    acquired = second.scalar(
                        text(
                            "SELECT "
                            "pg_try_advisory_xact_lock(:key)"
                        ),
                        {"key": QUOTA_LOCK_KEY},
                    )

                    assert acquired is False

            # The first transaction has ended.
            with second.begin():
                acquired = second.scalar(
                    text(
                        "SELECT "
                        "pg_try_advisory_xact_lock(:key)"
                    ),
                    {"key": QUOTA_LOCK_KEY},
                )

                assert acquired is True
