
import pytest

from sqlalchemy import create_engine, select, text, update
from sqlalchemy.orm import sessionmaker

from backend.ai.quota_service import (
    AIQuotaExceeded,
    AIQuotaUnavailable,
    QUOTA_LOCK_KEY,
    QuotaLimits,
    finish_ai_extraction,
    hash_visitor_ip,
    reserve_ai_extraction,
)
from backend.database.connection import engine
from backend.database.models import AIExtractionAttempt


@pytest.fixture
def quota_sessions():
    """Use a transaction-local temporary PostgreSQL table.

    This shadows the real quota table on this connection.
    No persistent application data is modified.
    """

    with engine.connect() as connection:
        transaction = connection.begin()

        connection.exec_driver_sql(
            """
            CREATE TEMP TABLE ai_extraction_attempts (
                id INTEGER GENERATED BY DEFAULT
                    AS IDENTITY PRIMARY KEY,
                visitor_hash VARCHAR(64) NOT NULL,
                created_at TIMESTAMPTZ NOT NULL
                    DEFAULT CURRENT_TIMESTAMP,
                lease_expires_at TIMESTAMPTZ NOT NULL,
                status VARCHAR(20) NOT NULL
                    DEFAULT 'reserved',
                CONSTRAINT ck_ai_test_status
                    CHECK (
                        status IN (
                            'reserved',
                            'completed',
                            'failed'
                        )
                    )
            ) ON COMMIT DROP
            """
        )

        try:
            yield sessionmaker(
                bind=connection,
                expire_on_commit=False,
                join_transaction_mode="create_savepoint",
            )
        finally:
            transaction.rollback()


def test_visitor_hash_is_stable_and_secret_based():
    first = hash_visitor_ip(
        "192.0.2.10",
        "a" * 40,
    )

    second = hash_visitor_ip(
        "192.0.2.10",
        "a" * 40,
    )

    different_secret = hash_visitor_ip(
        "192.0.2.10",
        "b" * 40,
    )

    assert first == second
    assert first != different_secret
    assert len(first) == 64
    assert "192.0.2.10" not in first


def test_visitor_hash_requires_valid_configuration():
    with pytest.raises(AIQuotaUnavailable):
        hash_visitor_ip("192.0.2.10", "short")

    with pytest.raises(AIQuotaUnavailable):
        hash_visitor_ip("not-an-ip", "a" * 40)


def test_reservation_can_be_completed(quota_sessions):
    attempt_id = reserve_ai_extraction(
        quota_sessions,
        "a" * 64,
    )

    assert isinstance(attempt_id, int)

    assert finish_ai_extraction(
        quota_sessions,
        attempt_id,
        succeeded=True,
    )

    with quota_sessions() as session:
        attempt = session.get(
            AIExtractionAttempt,
            attempt_id,
        )

        assert attempt.status == "completed"

    # Already completed requests cannot be completed twice.
    assert not finish_ai_extraction(
        quota_sessions,
        attempt_id,
        succeeded=True,
    )


def test_visitor_hourly_limit(quota_sessions):
    limits = QuotaLimits(
        visitor_per_hour=2,
        global_per_day=10,
        global_per_month=20,
    )

    for _ in range(2):
        attempt_id = reserve_ai_extraction(
            quota_sessions,
            "a" * 64,
            limits=limits,
        )

        finish_ai_extraction(
            quota_sessions,
            attempt_id,
            succeeded=True,
        )

    with pytest.raises(
        AIQuotaExceeded,
        match="visitor_hour",
    ):
        reserve_ai_extraction(
            quota_sessions,
            "a" * 64,
            limits=limits,
        )


