def test_global_concurrency_limit(quota_sessions):
    first_id = reserve_ai_extraction(
        quota_sessions,
        "a" * 64,
    )

    with pytest.raises(
        AIQuotaExceeded,
        match="concurrency",
    ):
        reserve_ai_extraction(
            quota_sessions,
            "b" * 64,
        )

        # A rejected reservation must not roll back
        # the already-granted reservation.
        with quota_sessions() as session:
            first_attempt = session.get(
                AIExtractionAttempt,
                first_id,
            )

            assert first_attempt is not None
            assert first_attempt.status == "reserved"

    finish_ai_extraction(
        quota_sessions,
        first_id,
        succeeded=False,
    )

    second_id = reserve_ai_extraction(
        quota_sessions,
        "b" * 64,
    )

    assert second_id != first_id


